# Parse DATABASE_URL without external dependency
def _parse_db_url(url):
    url = url.replace("postgres://", "").replace("postgresql://", "")
    creds, rest = url.split("@", 1)
    user, password = creds.split(":", 1)
    host_port, dbname = rest.rsplit("/", 1)
    host, port = (host_port.split(":", 1) if ":" in host_port else (host_port, "5432"))
    return {"NAME": dbname, "USER": user, "PASSWORD": password, "HOST": host, "PORT": port}

DATABASES = {
    "default": {
        "ENGINE": "django.db.backends.postgresql",
        **_parse_db_url(DATABASE_URL),
    }
}

